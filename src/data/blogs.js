const STORAGE_KEY = 'kriya_blogs';

export function getStoredBlogs() {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(INITIAL_BLOGS));
      return INITIAL_BLOGS;
    }
    const parsed = JSON.parse(raw);
    if (!Array.isArray(parsed) || parsed.length === 0) {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(INITIAL_BLOGS));
      return INITIAL_BLOGS;
    }
    // Merge any new initial seed items that might not be in older localStorage
    let updated = false;
    INITIAL_BLOGS.forEach(initBlog => {
      if (!parsed.some(p => p.id === initBlog.id || p.slug === initBlog.slug)) {
        parsed.push(initBlog);
        updated = true;
      }
    });
    if (updated) {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(parsed));
    }
    return parsed;
  } catch (e) {
    console.error('Error reading stored blogs:', e);
    return INITIAL_BLOGS;
  }
}

export function saveBlog(blogData) {
  const blogs = getStoredBlogs();
  const slug = blogData.slug || blogData.title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
  const id = blogData.id || slug || `post-${Date.now()}`;

  const existingIndex = blogs.findIndex(b => b.id === id || b.slug === slug);
  const updatedItem = {
    ...blogData,
    id,
    slug,
    date: blogData.date || new Date().toISOString().split('T')[0],
    views: blogData.views || Math.floor(Math.random() * 300) + 120
  };

  let newBlogs;
  if (existingIndex >= 0) {
    newBlogs = [...blogs];
    newBlogs[existingIndex] = updatedItem;
  } else {
    newBlogs = [updatedItem, ...blogs];
  }

  localStorage.setItem(STORAGE_KEY, JSON.stringify(newBlogs));
  return updatedItem;
}

export function deleteBlog(idOrSlug) {
  const blogs = getStoredBlogs();
  const filtered = blogs.filter(b => b.id !== idOrSlug && b.slug !== idOrSlug);
  localStorage.setItem(STORAGE_KEY, JSON.stringify(filtered));
  return filtered;
}

export function getBlogByIdOrSlug(idOrSlug) {
  const blogs = getStoredBlogs();
  return blogs.find(b => b.id === idOrSlug || b.slug === idOrSlug) || null;
}

export function resetDefaultBlogs() {
  localStorage.setItem(STORAGE_KEY, JSON.stringify(INITIAL_BLOGS));
  return INITIAL_BLOGS;
}